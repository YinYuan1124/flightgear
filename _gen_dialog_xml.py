# Extract decoded unique strings in a deterministic order
d = collections.OrderedDict()
for f in sorted(glob.glob('gui/dialogs/*.xml')):
    try:
        root = ET.parse(f).getroot()
    except Exception:
        continue
    for el in root.iter():
        if el.tag in ('label', 'legend'):
            s = (el.text or '').strip()
            if s:
                d[s] = None

lines = []
lines.append('<?xml version="1.0" encoding="UTF-8"?>')
lines.append('<!-- Static GUI dialog string translations (source -> target). -->')
lines.append('<PropertyList>')
for src in d:
    tgt = T.get(src)
    if not tgt:
        continue  # no translation -> fall back to English source
    lines.append('  <entry>')
    lines.append('    <source>%s</source>' % escape(src))
    lines.append('    <target>%s</target>' % escape(tgt))
    lines.append('  </entry>')
lines.append('</PropertyList>')

out = 'Translations/zh_CN/dialog.xml'
with open(out, 'w', encoding='utf-8') as o:
    o.write('\n'.join(lines) + '\n')

translated = sum(1 for s in d if T.get(s))
print('total unique:', len(d))
print('translated:', translated)
print('untranslated:', len(d) - translated)
print('wrote', out)
